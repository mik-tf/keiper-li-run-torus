#!/usr/bin/env python3
"""Generator for the T4 pilot chunk: exact Gaussian-integer data for zeros K0..K1-1 (0-indexed, k >= 1)
against the 48 dense weight vectors of ../code/vectors_c2.json (L = 594).  Pure Python integers.
Same grid as the paper 2 Lean code: gamma_mid = N / 2^30, half-width 1025 units of 2^-30.
Usage: python3 -I gen_pilot.py K0 K1 OUTFILE [NVEC]   (NVEC: use only the first NVEC vectors)
       python3 -I gen_pilot.py K0 K1 P3Lean/T4C00.lean 48 C00   (chunk module: data + native_decide theorem)
"""
import json, sys
from fractions import Fraction
from math import isqrt
CODE = "../code/"
S30 = 30
H = 2 ** 10 + 1
z = json.load(open(CODE + "z2000.json"))
V = json.load(open(CODE + "vectors_c2.json"))
assert V["den_exp"] == 50 and V["L"] == 594
VEC = [v["a"] for v in V["vectors"]][:int(sys.argv[4]) if len(sys.argv) > 4 else None]
NV = len(VEC); L = 594; VM = L - 1

def mid_N(i):
    man, e = z["gamma_mid_man_exp_rad_man_exp"][i][:2]
    f = Fraction(man) * Fraction(2) ** e
    N = round(f * 2 ** S30)
    assert abs(f - Fraction(N, 2 ** S30)) <= Fraction(1, 2 ** 31)
    return N

def zero_data(i, a):
    N = mid_N(i)
    Z = (N * N - 2 ** (2 * S30 - 2), N * 2 ** S30)
    D = N * N + 2 ** (2 * S30 - 2)
    # sum_j a_j Z^j D^(VM-j), Horner from the top
    P = (a[VM], 0); Dp = 1
    for j in range(VM - 1, -1, -1):
        Dp *= D
        P = (P[0] * Z[0] - P[1] * Z[1] + a[j] * Dp, P[0] * Z[1] + P[1] * Z[0])
    X, Y = P
    SA = sum(a)
    den = 2 ** 50 * D ** VM
    s = isqrt(2 ** 80 * (X * X + Y * Y)) + 1
    rho = -(-s // den)
    assert 2 ** 80 * (X * X + Y * Y) <= rho * rho * den * den
    Elo = (N - H) ** 2 + 2 ** (2 * S30 - 2)
    num = 2 ** 61 * rho * Elo + 2 ** 81 * SA * VM * H
    U = -(-num // (Elo * Elo))
    return rho, U


# ---- T4 chain mode: python3 -I gen_pilot.py K0 K1 P3Lean/T4C00.lean 22 C00 --t4 | python3 -I gen_pilot.py --t4-all
# The 22 chain positions (bsv i = weightsRev[chainIdx i]); rho, U per zero and position, plus per-position totals of U.
def chain22():
    C = json.load(open(CODE + "cert_c2_L594.json"))["result"]["cover"]["chain_vectors"]
    assert len(C) == 22
    import re
    src = open("P3Lean/T4Zero1Data.lean").read()
    lean = [int(x) for x in re.search(r"def chainIdx : List \u2115 := \[([0-9, ]*)\]", src).group(1).split(",")]
    assert lean == C, (lean, C)
    ids = [v["idx"] for v in json.load(open(CODE + "vectors_c2.json"))["vectors"]]
    assert ids == list(range(48))
    return C
def t4_chunk(nm, k0, k1, out):
    C = chain22(); cache = {}
    ns = []; RH = []; UU = []; tot = [0] * 22
    for k in range(k0, k1):
        N = mid_N(k); ns.append(N); rr = []; uu = []
        for pos, idx in enumerate(C):
            if (k, idx) not in cache: cache[(k, idx)] = zero_data(k, V["vectors"][idx]["a"])
            r, u = cache[(k, idx)]
            rr.append(r); uu.append(u); tot[pos] += u
        RH.append(rr); UU.append(uu)
    ll = lambda m: "[" + ",\n  ".join("[" + ", ".join(map(str, r)) + "]" for r in m) + "]"
    with open(out, "w") as f:
        f.write("-- generated by gen_pilot.py --t4 (do not edit). Chunk %s: zeros %d..%d (0-indexed), L = 594, the 22 chain positions.\n" % (nm, k0, k1 - 1))
        f.write("-- native_decide: the trust adds the Lean compiler and the GMP runtime (Lean.ofReduceBool).\n")
        f.write("import P3Lean.T4ChunkDef\nset_option maxRecDepth 100000\nnamespace P3Lean\nnamespace T4%s\n\n" % nm)
        f.write("def ns : List Nat := [%s]\n\n" % ", ".join(map(str, ns)))
        f.write("def rhoL : List (List Nat) := %s\n\ndef uL : List (List Nat) := %s\n\n" % (ll(RH), ll(UU)))
        f.write("def tot : List Nat := [%s]\n\n" % ", ".join(map(str, tot)))
        n = k1 - k0
        f.write("theorem len_ns : ns.length = %d := by decide\ntheorem len_rho : rhoL.length = %d := by decide\ntheorem len_u : uL.length = %d := by decide\n" % (n, n, n))
        f.write("theorem ge : \u2200 n \u2208 ns, 1025 \u2264 n := by decide\n")
        f.write("theorem good : \u2200 i, i < 22 \u2192 GoodC i ns rhoL uL := by native_decide\n")
        f.write("theorem tot_eq : \u2200 i, i < 22 \u2192 sumU i uL = tot.getD i 0 := by native_decide\n\nend T4%s\nend P3Lean\n#print axioms P3Lean.T4%s.good\n" % (nm, nm))
    print("wrote", out, k1 - k0, "zeros x 22 positions; totals", tot[:2])
if "--t4" in sys.argv:
    a = [x for x in sys.argv[1:] if x != "--t4"]
    t4_chunk(a[4], int(a[0]), int(a[1]), a[2]); sys.exit(0)
if "--t4-all" in sys.argv:
    import subprocess
    ps = [subprocess.Popen([sys.executable, "-I", "gen_pilot.py", str(1 + 100 * c), str(min(101 + 100 * c, 2000)), "P3Lean/T4C%02d.lean" % c, "22", "C%02d" % c, "--t4"]) for c in range(20)]
    sys.exit(max(p.wait() for p in ps))

k0, k1, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
assert k0 >= 1
rows = [(mid_N(i), [zero_data(i, a) for a in VEC]) for i in range(k0, k1)]
if len(sys.argv) > 5:
    nm = sys.argv[5]
    with open(out, "w") as f:
        f.write("-- generated by gen_pilot.py (do not edit). Chunk %s: zeros %d..%d (0-indexed), L = 594, %d vectors.\n" % (nm, k0, k1 - 1, NV))
        f.write("-- native_decide: the trust adds the Lean compiler and the GMP runtime (Lean.ofReduceBool).\n")
        f.write("import P3Lean.Core\nimport P3Lean.Weights\nset_option maxRecDepth 100000\nnamespace P3Lean\n\n")
        f.write("def rows%s : List (Nat \u00d7 List (Nat \u00d7 Nat)) := [%s]\n\n" % (nm, ",\n  ".join(
            "(%d, [%s])" % (n, ", ".join("(%d, %d)" % t for t in col)) for n, col in rows)))
        f.write("theorem ok_native_%s : checkChunk weightsRev rows%s = true := by native_decide\n\nend P3Lean\n#print axioms P3Lean.ok_native_%s\n" % (nm, nm, nm))
    print("wrote chunk", out, len(rows), "zeros x", NV, "vectors")
    sys.exit(0)
with open(out.replace("Data", "Weights"), "w") as f:
    f.write("-- generated by gen_pilot.py (do not edit). The 48 dense weight vectors, reversed (beta_593 first).\n")
    f.write("set_option maxRecDepth 100000\nnamespace P3Lean\n\n")
    f.write("def weightsRev : List (List Nat) := [%s]\n\n" % ",\n  ".join("[" + ", ".join(str(x) for x in reversed(a)) + "]" for a in VEC))
    f.write("end P3Lean\n")
with open(out, "w") as f:
    f.write("-- generated by gen_pilot.py (do not edit). Zeros %d..%d (0-indexed), L = 594, 48 vectors.\n" % (k0, k1 - 1))
    f.write("set_option maxRecDepth 100000\nnamespace P3Lean\n\n")
    f.write("def rows : List (Nat \u00d7 List (Nat \u00d7 Nat)) := [%s]\n\n" % ",\n  ".join(
        "(%d, [%s])" % (n, ", ".join("(%d, %d)" % t for t in col)) for n, col in rows))
    f.write("end P3Lean\n")
print("wrote", out, len(rows), "zeros x", NV, "vectors")
